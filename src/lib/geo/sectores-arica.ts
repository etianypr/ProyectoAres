function dentro(p: Coordenada, borde: [number, number][]): boolean {
  let adentro = false;
  for (let i = 0, j = borde.length - 1; i < borde.length; j = i++) {
    const [lat1, lng1] = borde[i];
    const [lat2, lng2] = borde[j];
    if (lat1 > p.lat !== lat2 > p.lat && p.lng < ((lng2 - lng1) * (p.lat - lat1)) / (lat2 - lat1) + lng1) adentro = !adentro;
  }
  return adentro;
}

/** El sector de un punto. Uno que cae fuera de todos (en la playa, en el mar o más
 *  allá de la hoja del plano) toma el del borde más cercano: siempre hay sector. */
export function sectorDe(p: Coordenada): SectorArica {
  for (const s of SECTORES_ARICA) if (dentro(p, LIMITES[s])) return s;
  let mejor: SectorArica = "Centro";
  let menor = Infinity;
  // En grados, con la longitud achicada a la latitud de Arica: alcanza para comparar.
  const cos = Math.cos((p.lat * Math.PI) / 180);
  for (const s of SECTORES_ARICA) {
    const borde = LIMITES[s];
    for (let i = 0, j = borde.length - 1; i < borde.length; j = i++) {
      const ax = (borde[j][1] - p.lng) * cos;
      const ay = borde[j][0] - p.lat;
      const bx = (borde[i][1] - p.lng) * cos;
      const by = borde[i][0] - p.lat;
      const largo = (bx - ax) ** 2 + (by - ay) ** 2;
      // El punto del lado más cercano al origen (que es `p`).
      const t = largo > 0 ? Math.min(1, Math.max(0, -(ax * (bx - ax) + ay * (by - ay)) / largo)) : 0;
      const d = Math.hypot(ax + t * (bx - ax), ay + t * (by - ay));
      if (d < menor) {
        menor = d;
        mejor = s;
      }
    }
  }
  return mejor;
}
